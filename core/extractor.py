def format_exp_date(value) -> Optional[str]:
    """Render an exp_date for user-facing display.

    Maps the no-expiry sentinels (2999-01-01, 9999-01-01, year >= 2900) to "Infinite";
    real dates are rendered as YYYY-MM-DD; NULL/empty stays None.
    """
    if not value:
        return None
    if isinstance(value, datetime):
        if value.year >= 2900:
            return NO_EXPIRY_DISPLAY
        return value.strftime("%Y-%m-%d")
    if isinstance(value, date):
        if value.year >= 2900:
            return NO_EXPIRY_DISPLAY
        return value.strftime("%Y-%m-%d")
    s = str(value).strip()
    if is_no_expiry_marker(s):
        return NO_EXPIRY_DISPLAY
    return s


def _normalize_text(text: str) -> str:
    if not text:
        return ""
    return re.sub(r"[^A-Z0-9]", "", text.upper())


def find_matching_authority(db: Session, authority_text: Optional[str]):
    """Resolves a raw authority string to a matched AuthorityLookup row (or None)."""
    raw_auth_norm = _normalize_text(authority_text)
    if not raw_auth_norm:
        return None
    authorities = db.query(AuthorityLookup).all()
    for auth in authorities:
        canon_norm = _normalize_text(auth.canonical_authority)
        alias_norms = [_normalize_text(a) for a in (auth.aliases or [])]
        if raw_auth_norm == canon_norm or raw_auth_norm in alias_norms:
            return auth
        elif any(
            a in raw_auth_norm for a in alias_norms if len(a) >= 3
        ) or (len(raw_auth_norm) >= 3 and raw_auth_norm in canon_norm):
            return auth
    return None


def enrich_certificate_metadata(
    data: CertificateExtractionSchema, db: Session
) -> CertificateExtractionSchema:
    """Deterministically normalizes and enriches LLM extraction using unified normalization rules."""
    if not db:
        return data

    norm_dict, _ = normalize_certificate_fields(
        raw_component=data.component,
        raw_supplier=data.supplier,
        raw_country=data.country,
        raw_certif_number=data.certif_number,
        raw_authority=data.authority,
        raw_issue_date=data.issue_date,
        raw_exp_date=data.exp_date,
        raw_cert_link=getattr(data, "cert_link", None),
        db=db,
    )

    if norm_dict.get("component"):
        data.component = norm_dict["component"]
    if norm_dict.get("supplier"):
        data.supplier = norm_dict["supplier"]
    if norm_dict.get("country"):
        data.country = norm_dict["country"]
    if norm_dict.get("authority"):
        data.authority = norm_dict["authority"]
    if norm_dict.get("certif_number"):
        data.certif_number = norm_dict["certif_number"]
    if norm_dict.get("issue_date_iso"):
        data.issue_date = norm_dict["issue_date_iso"]
    if norm_dict.get("exp_date_iso"):
        data.exp_date = norm_dict["exp_date_iso"]

    return data




def extract_certificate_data(
    raw_markdown: str, file_name: str, db_session: Optional[Session] = None
) -> CertificateExtractionSchema:
    """
    Extract structured data from raw Markdown text using an LLM and optionally enrich via DB.
    
    Args:
        raw_markdown: The markdown text output from the active OCR engine.
        file_name: The original filename, preserved for traceability.
        db_session: Optional active SQLAlchemy Session for lookup table enrichment.
        
    Returns:
        A validated and enriched CertificateExtractionSchema object.
    """
    # 1. Construct the LLM payload (engine formats system/user into its own template).
    from server.config import MAX_EXTRACTION_PROMPT_CHARS
    full_text = raw_markdown
    if len(raw_markdown) > MAX_EXTRACTION_PROMPT_CHARS:
        logger.warning(
            f"  Truncating extraction document from {len(raw_markdown)} to "
            f"{MAX_EXTRACTION_PROMPT_CHARS} chars to fit the LLM context window."
        )
        raw_markdown = raw_markdown[:MAX_EXTRACTION_PROMPT_CHARS]

    user_prompt = f"--- BEGIN DOCUMENT: {file_name} ---\n"
    user_prompt += f"{raw_markdown}\n"
    user_prompt += "--- END DOCUMENT ---\n\n"
    user_prompt += "Return ONLY the raw JSON output."

    # 2. Call the LLM engine to get the pure JSON string response (Full Reasoning Mode)
    from core.llm import generate_json
    from core.utils.vram import flush_gpu_cache, ensure_headroom
    from server.config import MIN_FREE_VRAM_MB
    flush_gpu_cache()
    ensure_headroom(MIN_FREE_VRAM_MB, "LLM extraction")
    raw_json_response = generate_json(
        system_prompt=config_extraction_system_prompt(),
        user_prompt=user_prompt,
        disable_thinking=False,
    )

    # 3. Parse and Validate with fallback
    try:
        parsed_data = CertificateExtractionSchema.model_validate_json(raw_json_response)
    except (json.JSONDecodeError, pydantic.ValidationError) as e:
        logger.warning(f"  JSON/Pydantic validation failed for {file_name}: {e}")
        logger.info("    Falling back to default 'Not Found' values to prevent crash.")
        
        parsed_data = CertificateExtractionSchema(
            component="Not Found",
            supplier="Not Found",
            country=None,
            certif_number="Not Found",
            authority="Not Found",
            issue_date=None,
            exp_date=None,
        )

    # 4. Enrich metadata with database lookups if db_session is provided
    if db_session is not None:
        parsed_data = enrich_certificate_metadata(parsed_data, db_session)

    return parsed_data


def find_existing_certificate(
    db: Session,
    file_name: Optional[str] = None,
    certif_number: Optional[str] = None,
    country: Optional[str] = None,
):
    """
    Locates an existing certificate record that a new ingestion should supersede.

    Anti-duplicate identity, evaluated in priority order:
      1. `certif_number` + `country` (case-insensitive) -- the strongest identity,
         used whenever both are known. Handles the same certificate re-ingested
         under a different filename, and multi-record CSV/Excel imports where many
         distinct certificates share the source `file_name`.
      2. `file_name` (case-insensitive) -- fallback identity used only when the
         certificate number is unavailable (e.g. a batch re-upload whose
         extraction produced no certif number).

    Returns the matching `CertificateMetadata` row or None.
    """
    from sqlalchemy import func
    from schemas.extraction import CertificateMetadata

    if certif_number and country:
        cn = str(certif_number).strip().lower()
        co = str(country).strip().lower()
        if cn and co:
            rec = (
                db.query(CertificateMetadata)
                .filter(
                    func.lower(CertificateMetadata.certif_number) == cn,
                    func.lower(CertificateMetadata.country) == co,
                )
                .first()
            )
            if rec is not None:
                return rec

    if file_name and str(file_name).strip():
        norm = str(file_name).strip().lower()
        rec = (
            db.query(CertificateMetadata)
            .filter(func.lower(CertificateMetadata.file_name) == norm)
            .first()
        )
        if rec is not None:
            return rec

    return None


def save_certificate_to_db(
    cert_data: CertificateExtractionSchema,
    raw_markdown: str,
    file_name: str,
    db: Optional[Session] = None,
    dedup_file_name: bool = True,
) -> CertificateMetadata:
    """
    Persists structured certificate metadata and vector-embedded chunks into PostgreSQL.

    Anti-duplicate behavior: if an existing record matches the incoming data
    (case-insensitive `file_name`, or `certif_number` + `country`), the existing
    record is updated in place and its vector chunks are replaced instead of
    inserting a duplicate row.

    Operation Steps:
      1. Performs lookup table enrichment on Pydantic certificate schema.
      2. Normalizes Pydantic fields to CertificateMetadata ORM values.
      3. Detects an existing duplicate and updates it, or creates a new record.
      4. Chunks layout-aware markdown text via chunk_for_qa().
      5. Computes 1024-dimensional BAAI/bge-m3 embeddings for every chunk.
      6. Binds chunks to the metadata record via certificate_id FK and commits.

    Args:
        cert_data: Validated extraction schema.
        raw_markdown: OCR markdown text.
        file_name: Source document file name.
        db: Optional session (auto-managed when None).
        dedup_file_name: When False, the case-insensitive file_name identity is
            skipped (used for manual entries that share a synthetic file name).

    Returns:
        CertificateMetadata: Persisted ORM metadata object.
    """
    close_session_on_exit = False
    if db is None:
        from storage.database import SessionLocal
        db = SessionLocal()
        close_session_on_exit = True

    try:
        # Perform lookup table enrichment before converting to ORM record
        cert_data = enrich_certificate_metadata(cert_data, db)

        # Normalize fields from Pydantic schema
        component = cert_data.component if cert_data.component != "Not Found" else None
        supplier = cert_data.supplier if cert_data.supplier != "Not Found" else None
        country = cert_data.country if cert_data.country != "Not Found" else None
        certif_number = cert_data.certif_number if getattr(cert_data, "certif_number", "Not Found") != "Not Found" else None
        authority = cert_data.authority if cert_data.authority != "Not Found" else None
        issue_dt = _parse_iso_date(cert_data.issue_date)
        exp_dt = _parse_iso_date(cert_data.exp_date)
        cert_link = getattr(cert_data, "cert_link", None) or None

        # ── Anti-duplicate: supersede an existing record if one matches ──
        existing = find_existing_certificate(
            db,
            file_name=file_name if dedup_file_name else None,
            certif_number=certif_number,
            country=country,
        )
        updated = False
        if existing is not None:
            cert_id = existing.certificate_id
            existing.component = component
            existing.supplier = supplier
            existing.country = country
            existing.certif_number = certif_number
            existing.authority = authority
            existing.issue_date = issue_dt
            existing.exp_date = exp_dt
            existing.cert_link = cert_link
            existing.file_name = file_name
            existing.created_at = datetime.utcnow()
            # Replace the old vector chunks so retrieval reflects the new content.
            db.query(CertificateChunk).filter(CertificateChunk.certificate_id == cert_id).delete()
            metadata_record = existing
            updated = True
        else:
            cert_id = f"cert_{uuid.uuid4().hex[:12]}"
            metadata_record = CertificateMetadata(
                certificate_id=cert_id,
                component=component,
                supplier=supplier,
                country=country,
                certif_number=certif_number,
                authority=authority,
                issue_date=issue_dt,
                exp_date=exp_dt,
                cert_link=cert_link,
                file_name=file_name
            )
            db.add(metadata_record)

        # 2. Chunk markdown text
        raw_chunks = chunk_for_qa(raw_markdown, file_name, document_id=cert_id)
        chunk_texts = [c.get("content", "") for c in raw_chunks]

        # 3. Compute 1024-d dense vector embeddings via BAAI/bge-m3
        logger.info(f"Computing 1024-d embeddings for {len(chunk_texts)} chunks...")
        embeddings = get_embeddings_batch(chunk_texts)

        # 4. Construct CertificateChunk ORM instances
        chunk_records = []
        for idx, chunk_info in enumerate(raw_chunks):
            pg_num = chunk_info.get("page_number")
            if isinstance(pg_num, str) and pg_num.isdigit():
                pg_num = int(pg_num)
            elif not isinstance(pg_num, int):
                pg_num = 1

            chunk_orm = CertificateChunk(
                certificate_id=cert_id,
                page_number=pg_num,
                raw_text=chunk_info.get("content", ""),
                embedding=embeddings[idx] if idx < len(embeddings) else [0.0] * 1024
            )
            chunk_records.append(chunk_orm)

        db.add_all(chunk_records)
        db.commit()
        db.refresh(metadata_record)
        metadata_record._is_updated = updated
        action = "Updated" if updated else "Successfully persisted"
        logger.info(f" {action} Certificate '{cert_id}' with {len(chunk_records)} chunks to PostgreSQL.")
        
        # Log notification for PDF document extraction & persistence
        try:
            from schemas.extraction import NotificationItem
            notif = NotificationItem(
                title=f"PDF Certificate Ingested ({component})",
                message=f"Extracted compliance certificate #{certif_number} for component '{component}' ({country}) from '{file_name}'. Authority: {authority}.",
                category="extraction",
                is_read=False,
                created_at=datetime.utcnow()
            )
            db.add(notif)
            db.commit()
        except Exception as ex:
            logger.debug(f"Error logging PDF extraction notification: {ex}")

        # Trigger automated backup in background thread
        from storage.backup import trigger_async_backup
        trigger_async_backup()
        
        return metadata_record
    except Exception as e:
        db.rollback()
        logger.error(f" Database error persisting Certificate '{cert_id}': {e}")
        raise
    finally:
        if close_session_on_exit:
            db.close()
